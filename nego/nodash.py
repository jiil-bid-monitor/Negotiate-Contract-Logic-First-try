"""사람이 보는 글에서 긴 줄표를 뺌(11/25 사용자, AI 티) — 텔레그램·메일·리포트·서류_확인.txt·엑셀 안내·웹앱 오류를 내보내기 직전에."""
import re


def no_dash(text: str) -> str:
    """'…다 — X' → '…다. X', 'A — B' → 'A: B', 값 없음 표시 '>—<' → '>-<'. 붙여 쓴 줄표는 그대로."""
    text = re.sub(r"([다요]) +— +", r"\1. ", text.replace(">—<", ">-<"))
    return re.sub(r" +— +", ": ", text)
